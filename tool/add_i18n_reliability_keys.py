def merge_locale(code: str) -> None:
    path = ROOT / f"{code}.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    src = NEW["en"] if code == "en" else LOCALES.get(code) or {}
    if code != "en" and len(src) < len(NEW["en"]):
        # Fill missing from English for locales without full table yet
        for k, v in NEW["en"].items():
            src.setdefault(k, v)
    for k, v in (NEW["en"] if code == "en" else src).items():
        if code == "en":
            data[k] = v
        elif k in src:
            data[k] = src[k]
        elif k not in data:
            data[k] = NEW["en"][k]
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    merge_locale("en")
    merge_locale("de")
    for code in ("fr", "es", "el", "zh", "ar"):
        merge_locale(code)
    print("Merged i18n keys into locale files.")


if __name__ == "__main__":
    main()
